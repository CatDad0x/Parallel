// Exports ABIs from the Foundry build into packages/shared/src/abis.ts. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const out = join(root, "contracts/out");
const items = {
  oracleHub: "OracleHub.sol/OracleHub.json",
  exchange: "SimExchange.sol/SimExchange.json",
  hedgeBook: "HedgeBook.sol/HedgeBook.json",
  vault: "ParallelVault.sol/ParallelVault.json",
  factory: "VaultFactory.sol/VaultFactory.json",
  faucet: "Faucet.sol/Faucet.json",
  router: "ParallelRouter.sol/ParallelRouter.json",
  token: "MockToken.sol/MockToken.json",
  demoPyth: "DemoPyth.sol/DemoPyth.json",
  morpho: "Morpho.sol/Morpho.json",
  irm: "KinkedIrm.sol/KinkedIrm.json",
};
let src = "// Generated by scripts/export-abis.mjs. Do not edit.\n";
for (const [name, file] of Object.entries(items)) {
  const { abi } = JSON.parse(readFileSync(join(out, file), "utf8"));
  src += `export const ${name}Abi = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(join(root, "packages/shared/src/abis.ts"), src);
console.log("wrote packages/shared/src/abis.ts");
